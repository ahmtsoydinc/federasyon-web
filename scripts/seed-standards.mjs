async function run() {
  console.log('Standart verileri ekleniyor...')
  await client.execute('DELETE FROM "AnimalStandard"')
  console.log('Mevcut standartlar silindi.')

  const chunkSize = 50
  let inserted = 0
  for (let i = 0; i < standards.length; i += chunkSize) {
    const chunk = standards.slice(i, i + chunkSize)
    for (const [animalType, breed, species, color] of chunk) {
      await client.execute({
        sql: 'INSERT INTO "AnimalStandard" ("animalType","breed","species","color") VALUES (?,?,?,?)',
        args: [animalType, breed, species, color],
      })
      inserted++
    }
    console.log(`  ${inserted}/${standards.length} eklendi...`)
  }
  console.log(`\n✓ Toplam ${inserted} standart başarıyla eklendi.`)
}

run().catch(e => { console.error('Hata:', e.message); process.exit(1) })
